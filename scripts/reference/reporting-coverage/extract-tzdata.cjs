#!/usr/bin/env node
'use strict';

/**
 * Regenerates tzdata.json, the pinned IANA Time Zone Database subset the
 * reference model reads, from an IANA release tarball.
 *
 *   node scripts/reference/reporting-coverage/extract-tzdata.cjs <tzdataYYYYx.tar.gz> <sha512> [zone ...]
 *
 * The SHA-512 is checked before anything is read. The output keeps the zic
 * source lines (Zone, Rule, and Link) for the zones the vectors use, byte for
 * byte, so a reader can diff them against the release, plus every zone and
 * link name in the release, so the model can tell a valid IANA name it does
 * not carry from a name that is not IANA at all. Without zone arguments it
 * re-extracts the zones already in tzdata.json.
 *
 * It also compiles the release with the reference compiler, zic(8), and
 * records each zone's UTC offset changes from zdump(8) for 1970 through 2040,
 * an independent oracle the tests check tz.cjs against. zic and zdump must be
 * on PATH (Debian and Ubuntu: libc-bin).
 */

const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const OUT = path.join(__dirname, 'tzdata.json');
// The files zic builds the default database from (backzone is opt-in).
const DATA_FILES = ['africa', 'antarctica', 'asia', 'australasia', 'europe', 'northamerica', 'southamerica', 'etcetera', 'backward'];

function main(argv) {
  const [tarball, sha512, ...requested] = argv;
  if (!tarball || !/^[0-9a-f]{128}$/.test(sha512 || '')) {
    console.error('usage: extract-tzdata.cjs <tzdataYYYYx.tar.gz> <sha512-hex> [zone ...]');
    return 2;
  }
  const bytes = fs.readFileSync(tarball);
  const actual = crypto.createHash('sha512').update(bytes).digest('hex');
  if (actual !== sha512) {
    console.error(`sha512 mismatch: expected ${sha512}, got ${actual}`);
    return 1;
  }
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tzdata-'));
  execFileSync('tar', ['-xzf', path.resolve(tarball), '-C', dir]);
  const version = fs.readFileSync(path.join(dir, 'version'), 'utf8').trim();

  const zones = new Map(); // name -> lines
  const rules = new Map(); // name -> lines
  const links = new Map(); // link name -> target
  for (const file of DATA_FILES) {
    const lines = fs.readFileSync(path.join(dir, file), 'utf8').split('\n');
    let current = null;
    for (const raw of lines) {
      const line = raw.replace(/#.*$/, '').replace(/\s+$/, '');
      if (line === '') continue;
      const fields = line.trim().split(/\s+/);
      if (/^\s/.test(line)) {
        if (current) current.push(raw.replace(/\s+#.*$/, '').replace(/\s+$/, ''));
        continue;
      }
      current = null;
      if (fields[0] === 'Zone') {
        current = [raw.replace(/\s+#.*$/, '').replace(/\s+$/, '')];
        zones.set(fields[1], current);
      } else if (fields[0] === 'Rule') {
        if (!rules.has(fields[1])) rules.set(fields[1], []);
        rules.get(fields[1]).push(raw.replace(/\s+#.*$/, '').replace(/\s+$/, ''));
      } else if (fields[0] === 'Link') {
        links.set(fields[2], fields[1]);
      }
    }
  }
  const previous = fs.existsSync(OUT) ? JSON.parse(fs.readFileSync(OUT, 'utf8')) : null;
  const wanted = requested.length > 0 ? requested : previous ? [...Object.keys(previous.links), ...Object.keys(previous.zones)] : [];
  const out = {
    $comment:
      'Pinned IANA Time Zone Database subset for the reporting-coverage reference model. Generated by extract-tzdata.cjs; do not edit by hand.',
    version,
    source: `https://data.iana.org/time-zones/releases/tzdata${version}.tar.gz`,
    source_sha512: sha512,
    names: [...new Set([...zones.keys(), ...links.keys()])].sort(),
    links: {},
    zones: {},
    rules: {},
  };
  for (const name of wanted) {
    let target = name;
    while (links.has(target)) {
      out.links[target] = links.get(target);
      target = links.get(target);
    }
    if (!zones.has(target)) throw new Error(`${name} is not a zone in tzdata ${version}`);
    const zoneLines = zones.get(target);
    out.zones[target] = zoneLines;
    for (const zoneLine of zoneLines) {
      const fields = zoneLine.trim().split(/\s+/);
      const rulesField = fields[0] === 'Zone' ? fields[3] : fields[1];
      if (rules.has(rulesField)) out.rules[rulesField] = rules.get(rulesField);
    }
  }
  out.zic_transitions = zicTransitions(dir, Object.keys(out.zones));
  fs.rmSync(dir, { recursive: true, force: true });
  out.zones = Object.fromEntries(Object.entries(out.zones).sort(([a], [b]) => (a < b ? -1 : 1)));
  out.rules = Object.fromEntries(Object.entries(out.rules).sort(([a], [b]) => (a < b ? -1 : 1)));
  out.links = Object.fromEntries(Object.entries(out.links).sort(([a], [b]) => (a < b ? -1 : 1)));
  fs.writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');
  console.log(`wrote ${path.relative(process.cwd(), OUT)}: tzdata ${version}, ${Object.keys(out.zones).length} zones`);
  return 0;
}

const ZIC_RANGE = [1970, 2041];

/** Per zone, the UTC offset in seconds at the start of the range and each change as [ISO instant, offset], from zic and zdump. */
function zicTransitions(dir, zoneNames) {
  const compiled = path.join(dir, 'zoneinfo');
  execFileSync('zic', ['-d', compiled, ...DATA_FILES.map(file => path.join(dir, file))]);
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  const out = { range: ZIC_RANGE, zones: {} };
  for (const zone of zoneNames) {
    const text = execFileSync('zdump', ['-v', '-c', ZIC_RANGE.join(','), path.join(compiled, zone)], { encoding: 'utf8' });
    const changes = [];
    let previous = null;
    for (const line of text.split('\n')) {
      const m = / \w{3} (\w{3}) +(\d+) (\d\d):(\d\d):(\d\d) (\d+) UT = .* gmtoff=(-?\d+)$/.exec(line);
      if (!m) continue;
      const at = Date.UTC(Number(m[6]), months.indexOf(m[1]), Number(m[2]), Number(m[3]), Number(m[4]), Number(m[5]));
      const offset = Number(m[7]);
      // zdump prints the second before each transition and the transition itself.
      if (previous !== null && offset !== previous) changes.push([new Date(at).toISOString().replace('.000Z', 'Z'), offset]);
      previous = offset;
    }
    // zdump -i's first line gives the offset in effect at the start of the range.
    const initial = /^-\t-\t([+-])(\d\d)(\d\d)?(\d\d)?/m.exec(
      execFileSync('zdump', ['-i', '-c', ZIC_RANGE.join(','), path.join(compiled, zone)], { encoding: 'utf8' }),
    );
    const sign = initial[1] === '-' ? -1 : 1;
    out.zones[zone] = { initial: sign * (Number(initial[2]) * 3600 + Number(initial[3] || 0) * 60 + Number(initial[4] || 0)), changes };
  }
  return out;
}

if (require.main === module) process.exit(main(process.argv.slice(2)));
