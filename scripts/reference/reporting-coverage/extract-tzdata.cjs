#!/usr/bin/env node
'use strict';

/**
 * Regenerates tzdata.json, the pinned IANA Time Zone Database the reference
 * model reads, from an IANA release tarball.
 *
 *   node scripts/reference/reporting-coverage/extract-tzdata.cjs <tzdataYYYYx.tar.gz> <sha512>
 *
 * The SHA-512 is checked before anything is read. The output carries every
 * Zone, Rule, and Link of the default zic build (the files below; backzone is
 * opt-in and excluded, as in every mainstream distribution), so any IANA zone
 * or link name works. Each Zone and Rule keeps its zic source lines byte for
 * byte, minus comments, so a reader can diff them against the release. That
 * is the whole database: about 3,000 zone lines and 2,100 rule lines.
 *
 * It also compiles the release with the reference compiler, zic(8), and
 * records, per zone, a SHA-256 digest of the zone's UTC offset changes from
 * zdump(8) for 1970 through 2040: an independent oracle the tests check
 * tz.cjs against, for every zone, without carrying every transition. zic and
 * zdump must be on PATH (Debian and Ubuntu: libc-bin). The output depends only
 * on the tarball, so regenerating from the same release is byte-identical.
 */

const crypto = require('node:crypto');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const OUT = path.join(__dirname, 'tzdata.json');
// The files zic builds the default database from (backzone is opt-in).
const DATA_FILES = ['africa', 'antarctica', 'asia', 'australasia', 'europe', 'northamerica', 'southamerica', 'etcetera', 'backward'];
const ZIC_RANGE = [1970, 2041];

function main(argv) {
  const [tarball, sha512] = argv;
  if (!tarball || !/^[0-9a-f]{128}$/.test(sha512 || '')) {
    console.error('usage: extract-tzdata.cjs <tzdataYYYYx.tar.gz> <sha512-hex>');
    return 2;
  }
  const bytes = fs.readFileSync(tarball);
  const actual = crypto.createHash('sha512').update(bytes).digest('hex');
  if (actual !== sha512) {
    console.error(`sha512 mismatch: expected ${sha512}, got ${actual}`);
    return 1;
  }
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tzdata-'));
  execFileSync('tar', ['-xzf', path.resolve(tarball), '-C', dir]);
  const version = fs.readFileSync(path.join(dir, 'version'), 'utf8').trim();

  const zones = new Map(); // name -> lines
  const rules = new Map(); // name -> lines
  const links = new Map(); // link name -> target
  const strip = raw => raw.replace(/\s+#.*$/, '').replace(/\s+$/, '');
  for (const file of DATA_FILES) {
    const lines = fs.readFileSync(path.join(dir, file), 'utf8').split('\n');
    let current = null;
    for (const raw of lines) {
      const line = raw.replace(/#.*$/, '').replace(/\s+$/, '');
      if (line === '') continue;
      const fields = line.trim().split(/\s+/);
      if (/^\s/.test(line)) {
        if (current) current.push(strip(raw));
        continue;
      }
      current = null;
      if (fields[0] === 'Zone') {
        if (zones.has(fields[1])) throw new Error(`zone ${fields[1]} defined twice`);
        current = [strip(raw)];
        zones.set(fields[1], current);
      } else if (fields[0] === 'Rule') {
        if (!rules.has(fields[1])) rules.set(fields[1], []);
        rules.get(fields[1]).push(strip(raw));
      } else if (fields[0] === 'Link') {
        links.set(fields[2], fields[1]);
      }
    }
  }
  for (const [name, target] of links) {
    if (!zones.has(target) && !links.has(target)) throw new Error(`link ${name} -> ${target} has no zone`);
  }
  const sorted = map => [...map.entries()].sort(([a], [b]) => (a < b ? -1 : 1));
  const oracle = zicDigests(dir, [...zones.keys()].sort());
  fs.rmSync(dir, { recursive: true, force: true });

  // One zone, rule set, or link per line keeps the file diffable and about 15% smaller than indented JSON.
  const entries = list => list.map(([name, value]) => `    ${JSON.stringify(name)}: ${JSON.stringify(value)}`).join(',\n');
  const text = [
    '{',
    `  "$comment": ${JSON.stringify('Pinned IANA Time Zone Database (the default zic build: every Zone, Rule, and Link) for the reporting-coverage reference model. Generated by extract-tzdata.cjs; do not edit by hand.')},`,
    `  "version": ${JSON.stringify(version)},`,
    `  "source": ${JSON.stringify(`https://data.iana.org/time-zones/releases/tzdata${version}.tar.gz`)},`,
    `  "source_sha512": ${JSON.stringify(sha512)},`,
    `  "links": {\n${entries(sorted(links))}\n  },`,
    `  "zones": {\n${entries(sorted(zones))}\n  },`,
    `  "rules": {\n${entries(sorted(rules))}\n  },`,
    `  "zic_check": {\n    "$comment": ${JSON.stringify(ZIC_CHECK_COMMENT)},\n    "range": ${JSON.stringify(ZIC_RANGE)},\n    "zones": {\n${entries(oracle).replace(/^ {4}/gm, '      ')}\n    }\n  }`,
    '}',
    '',
  ].join('\n');
  JSON.parse(text);
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(process.cwd(), OUT)}: tzdata ${version}, ${zones.size} zones, ${links.size} links, ${rules.size} rule sets, ${text.length} bytes`);
  return 0;
}

const ZIC_CHECK_COMMENT =
  'Per zone, [count, sha256] of its UTC offset changes inside range (from January 1 of the first year to January 1 of the second, UTC) as zic(8) compiles them and zdump(8) prints them. The digest is over JSON.stringify([initial, changes]): initial is the offset in seconds at the start of the range, and changes lists [unix_seconds, offset_seconds] for each change.';

/** Per zone, [change count, digest] of its UTC offset changes in ZIC_RANGE, from zic and zdump. */
function zicDigests(dir, zoneNames) {
  const compiled = path.join(dir, 'zoneinfo');
  execFileSync('zic', ['-d', compiled, ...DATA_FILES.map(file => path.join(dir, file))]);
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  const out = [];
  for (const zone of zoneNames) {
    const text = execFileSync('zdump', ['-v', '-c', ZIC_RANGE.join(','), path.join(compiled, zone)], { encoding: 'utf8' });
    const changes = [];
    let previous = null;
    for (const line of text.split('\n')) {
      const m = / \w{3} (\w{3}) +(\d+) (\d\d):(\d\d):(\d\d) (\d+) UT = .* gmtoff=(-?\d+)$/.exec(line);
      if (!m) continue;
      const at = Date.UTC(Number(m[6]), months.indexOf(m[1]), Number(m[2]), Number(m[3]), Number(m[4]), Number(m[5])) / 1000;
      const offset = Number(m[7]);
      // zdump prints the second before each transition and the transition itself.
      if (previous !== null && offset !== previous) changes.push([at, offset]);
      previous = offset;
    }
    // zdump -i's first line gives the offset in effect at the start of the range.
    const initial = /^-\t-\t([+-])(\d\d)(\d\d)?(\d\d)?/m.exec(
      execFileSync('zdump', ['-i', '-c', ZIC_RANGE.join(','), path.join(compiled, zone)], { encoding: 'utf8' }),
    );
    const sign = initial[1] === '-' ? -1 : 1;
    const start = sign * (Number(initial[2]) * 3600 + Number(initial[3] || 0) * 60 + Number(initial[4] || 0));
    out.push([zone, [changes.length, digest(start, changes)]]);
  }
  return out;
}

/** The oracle digest; tests compute the same from tz.cjs. */
function digest(initial, changes) {
  return crypto.createHash('sha256').update(JSON.stringify([initial, changes])).digest('hex');
}

module.exports = { digest, ZIC_RANGE };

if (require.main === module) process.exit(main(process.argv.slice(2)));
