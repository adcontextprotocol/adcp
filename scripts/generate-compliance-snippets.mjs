#!/usr/bin/env node

/**
 * Generate deterministic Mintlify snippets from compliance machine sources.
 *
 * Sources:
 *   - static/schemas/source/enums/error-code.json
 *   - dist/compliance/latest/index.json and its universal storyboard YAML
 *
 * Usage:
 *   node scripts/generate-compliance-snippets.mjs
 *   node scripts/generate-compliance-snippets.mjs --check
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ERROR_CODE_SCHEMA = path.join(
  REPO_ROOT,
  'static/schemas/source/enums/error-code.json',
);
const COMPLIANCE_DIR = path.join(REPO_ROOT, 'dist/compliance/latest');
const COMPLIANCE_INDEX = path.join(COMPLIANCE_DIR, 'index.json');
const OUTPUT_DIR = path.join(REPO_ROOT, 'docs/snippets');
const CATALOG = path.join(
  REPO_ROOT,
  'docs/building/verification/compliance-catalog.mdx',
);
const CHECK = process.argv.includes('--check');
const GENERATED_MARKER = 'This file is generated by scripts/generate-compliance-snippets.mjs.';
const STORYBOARD_SLUG = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;
const ERROR_CODE = /^[A-Z][A-Z0-9_]*$/;
const RECOVERY_VALUES = new Set(['correctable', 'transient', 'terminal']);
const UNIVERSAL_SUPPORT_ARTIFACTS = new Set([
  'fictional-entities',
  'runner-output-contract',
  'storyboard-schema',
]);

const OUTPUTS = {
  'compliance-error-codes.mdx': {
    component: 'ComplianceErrorCodes',
    importPath: '/docs/snippets/compliance-error-codes.mdx',
  },
  'compliance-storyboard-inventory.mdx': {
    component: 'ComplianceStoryboardInventory',
    importPath: '/docs/snippets/compliance-storyboard-inventory.mdx',
  },
};

function compareText(a, b) {
  return a < b ? -1 : a > b ? 1 : 0;
}

function isPlainObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function isNonemptyString(value) {
  return typeof value === 'string' && value.trim().length > 0;
}

function readJson(filePath) {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'));
  } catch (error) {
    throw new Error(`Unable to read JSON source ${path.relative(REPO_ROOT, filePath)}: ${error.message}`);
  }
}

function escapeTableCell(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/{/g, '&#123;')
    .replace(/}/g, '&#125;')
    .replace(/\|/g, '&#124;')
    .replace(/\s+/g, ' ')
    .trim();
}

function escapeMdxBlock(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/{/g, '&#123;')
    .replace(/}/g, '&#125;')
    .trim();
}

function generatedHeader(sourcePaths) {
  return [
    '{/*',
    `  ${GENERATED_MARKER}`,
    '  Do not edit it by hand. Regenerate with `npm run build:compliance`.',
    `  Sources: ${sourcePaths.join(', ')}`,
    '*/}',
    '',
  ].join('\n');
}

function assertCompleteErrorTaxonomy(schema) {
  if (!Array.isArray(schema.enum)) {
    throw new Error('error-code.json must contain an enum array');
  }
  if (!isPlainObject(schema.enumDescriptions)) {
    throw new Error('error-code.json must contain enumDescriptions');
  }
  if (!isPlainObject(schema.enumMetadata)) {
    throw new Error('error-code.json must contain enumMetadata');
  }

  const codes = new Set();
  for (const code of schema.enum) {
    if (!isNonemptyString(code) || !ERROR_CODE.test(code)) {
      throw new Error(`error-code.json contains invalid enum value: ${JSON.stringify(code)}`);
    }
    if (codes.has(code)) throw new Error(`error-code.json contains duplicate enum value: ${code}`);
    codes.add(code);
  }
  const descriptionCodes = new Set(Object.keys(schema.enumDescriptions));
  const metadataCodes = new Set(
    Object.keys(schema.enumMetadata).filter(key => key !== '$comment'),
  );
  const problems = [];

  for (const code of codes) {
    if (!descriptionCodes.has(code)) problems.push(`${code}: missing enumDescriptions entry`);
    if (!metadataCodes.has(code)) problems.push(`${code}: missing enumMetadata entry`);
    if (descriptionCodes.has(code) && !isNonemptyString(schema.enumDescriptions[code])) {
      problems.push(`${code}: enumDescriptions entry must be a nonempty string`);
    }
    const metadata = schema.enumMetadata[code];
    if (metadataCodes.has(code) && !isPlainObject(metadata)) {
      problems.push(`${code}: enumMetadata entry must be an object`);
    } else if (metadataCodes.has(code)) {
      if (!RECOVERY_VALUES.has(metadata.recovery)) {
        problems.push(`${code}: enumMetadata.recovery must be correctable, transient, or terminal`);
      }
      if (!isNonemptyString(metadata.suggestion)) {
        problems.push(`${code}: enumMetadata.suggestion must be a nonempty string`);
      }
    }
  }
  for (const code of descriptionCodes) {
    if (!codes.has(code)) problems.push(`${code}: description exists outside enum`);
  }
  for (const code of metadataCodes) {
    if (!codes.has(code)) problems.push(`${code}: metadata exists outside enum`);
  }

  if (problems.length) {
    throw new Error(`Error-code taxonomy is incomplete:\n  - ${problems.sort(compareText).join('\n  - ')}`);
  }
}

function renderErrorCodes(schema) {
  assertCompleteErrorTaxonomy(schema);
  const lines = [
    generatedHeader(['static/schemas/source/enums/error-code.json']),
    '| Code | Recovery | Suggested action |',
    '|------|----------|------------------|',
  ];

  for (const code of [...schema.enum].sort(compareText)) {
    const metadata = schema.enumMetadata[code];
    lines.push(
      `| \`${code}\` | ${escapeTableCell(metadata.recovery)} | ${escapeTableCell(metadata.suggestion)} |`,
    );
  }
  lines.push('', '### Full descriptions', '', '<AccordionGroup>');
  for (const code of [...schema.enum].sort(compareText)) {
    const metadata = schema.enumMetadata[code];
    lines.push(
      `<Accordion title="${code} — ${metadata.recovery}">`,
      '',
      `**Suggested action:** ${escapeMdxBlock(metadata.suggestion)}`,
      '',
      escapeMdxBlock(schema.enumDescriptions[code]),
      '',
      '</Accordion>',
    );
  }
  lines.push('</AccordionGroup>');
  return `${lines.join('\n')}\n`;
}

function loadGradedStoryboards(index, complianceDir = COMPLIANCE_DIR) {
  if (!Array.isArray(index.universal)) {
    throw new Error('dist/compliance/latest/index.json must contain a universal array');
  }

  const storyboards = [];
  const seen = new Set();
  const universalDir = path.join(complianceDir, 'universal');
  for (const slug of [...index.universal].sort(compareText)) {
    if (!isNonemptyString(slug) || !STORYBOARD_SLUG.test(slug)) {
      throw new Error(`Compliance index contains invalid universal storyboard slug: ${JSON.stringify(slug)}`);
    }
    if (seen.has(slug)) {
      throw new Error(`Compliance index contains duplicate universal storyboard slug: ${slug}`);
    }
    seen.add(slug);
    const yamlPath = path.join(universalDir, `${slug}.yaml`);
    let stat;
    try {
      stat = fs.lstatSync(yamlPath);
    } catch {
      throw new Error(`Compliance index references missing storyboard source: ${yamlPath}`);
    }
    if (!stat.isFile()) {
      throw new Error(`Compliance storyboard source must be a regular file: ${yamlPath}`);
    }
    const document = yaml.load(fs.readFileSync(yamlPath, 'utf8'));
    if (UNIVERSAL_SUPPORT_ARTIFACTS.has(slug)) {
      if (isPlainObject(document) && Array.isArray(document.phases)) {
        throw new Error(`Universal support artifact ${slug} unexpectedly declares graded phases`);
      }
      continue;
    }
    if (!isPlainObject(document)) {
      throw new Error(`Universal inventory entry ${slug} must contain a YAML object`);
    }
    if (!Array.isArray(document.phases)) {
      throw new Error(
        `Universal inventory entry ${slug} is neither a graded storyboard nor a known support artifact`,
      );
    }
    if (!isNonemptyString(document.title) || !isNonemptyString(document.summary)) {
      throw new Error(`Graded storyboard ${slug} must declare both title and summary`);
    }
    storyboards.push({
      slug,
      title: document.title,
      summary: document.summary,
    });
  }
  return storyboards;
}

function renderStoryboardInventory(index, complianceDir = COMPLIANCE_DIR) {
  const storyboards = loadGradedStoryboards(index, complianceDir);
  const lines = [
    generatedHeader([
      'dist/compliance/latest/index.json',
      'dist/compliance/latest/universal/*.yaml',
    ]),
    '| Graded storyboard | Purpose | Source |',
    '|-------------------|---------|--------|',
  ];

  for (const storyboard of storyboards) {
    lines.push(
      `| \`${storyboard.slug}\` | ${escapeTableCell(storyboard.summary)} | [YAML](https://adcontextprotocol.org/compliance/latest/universal/${storyboard.slug}.yaml) |`,
    );
  }
  return `${lines.join('\n')}\n`;
}

function assertCatalogConsumesOutputs(catalogContent) {
  const problems = [];
  for (const { component, importPath } of Object.values(OUTPUTS)) {
    const importPattern = new RegExp(
      `import\\s+${component}\\s+from\\s+["']${importPath.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}["'];?`,
    );
    const usagePattern = new RegExp(`<${component}\\s*/>`);
    if (!importPattern.test(catalogContent)) {
      problems.push(`missing import for ${component} from ${importPath}`);
    }
    if (!usagePattern.test(catalogContent)) {
      problems.push(`missing <${component} /> usage`);
    }
  }
  if (problems.length) {
    throw new Error(
      `docs/building/verification/compliance-catalog.mdx does not consume generated snippets:\n  - ${problems.join('\n  - ')}`,
    );
  }
}

function generatedFiles(outputDir) {
  if (!fs.existsSync(outputDir)) return [];
  return fs.readdirSync(outputDir, { withFileTypes: true })
    .filter(entry => entry.isFile() && entry.name.endsWith('.mdx'))
    .filter(entry => fs.readFileSync(path.join(outputDir, entry.name), 'utf8').includes(GENERATED_MARKER))
    .map(entry => entry.name)
    .sort(compareText);
}

function writeOrCheck(outputs, { check = CHECK, outputDir = OUTPUT_DIR } = {}) {
  const stale = [];
  if (!check) fs.mkdirSync(outputDir, { recursive: true });

  const expected = new Set(Object.keys(outputs));
  const orphaned = generatedFiles(outputDir).filter(filename => !expected.has(filename));
  if (check) {
    stale.push(...orphaned.map(filename => path.relative(REPO_ROOT, path.join(outputDir, filename))));
  } else {
    for (const filename of orphaned) fs.unlinkSync(path.join(outputDir, filename));
  }

  for (const [filename, content] of Object.entries(outputs).sort(([a], [b]) => compareText(a, b))) {
    const outputPath = path.join(outputDir, filename);
    if (check) {
      if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== content) {
        stale.push(path.relative(REPO_ROOT, outputPath));
      }
    } else {
      fs.writeFileSync(outputPath, content);
    }
  }

  if (stale.length) {
    throw new Error(
      `Generated compliance snippets are stale:\n  - ${stale.join('\n  - ')}\nRun \`npm run build:compliance\` and commit the results.`,
    );
  }
}

function main() {
  if (!fs.existsSync(COMPLIANCE_INDEX)) {
    throw new Error(
      'dist/compliance/latest/index.json is missing. Run `npm run build:compliance` before checking snippets.',
    );
  }

  const outputs = {
    'compliance-error-codes.mdx': renderErrorCodes(readJson(ERROR_CODE_SCHEMA)),
    'compliance-storyboard-inventory.mdx': renderStoryboardInventory(readJson(COMPLIANCE_INDEX)),
  };
  assertCatalogConsumesOutputs(fs.readFileSync(CATALOG, 'utf8'));
  writeOrCheck(outputs);
  console.log(
    CHECK
      ? `✓ compliance snippets are current (${Object.keys(outputs).length} files)`
      : `✓ generated ${Object.keys(outputs).length} compliance snippets`,
  );
}

try {
  const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
  if (isMain) main();
} catch (error) {
  console.error(error.message || error);
  process.exit(1);
}

export {
  GENERATED_MARKER,
  assertCatalogConsumesOutputs,
  assertCompleteErrorTaxonomy,
  escapeTableCell,
  escapeMdxBlock,
  generatedFiles,
  loadGradedStoryboards,
  renderErrorCodes,
  renderStoryboardInventory,
  writeOrCheck,
};
