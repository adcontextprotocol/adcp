const { describe, it } = require('node:test');
const assert = require('node:assert/strict');
const { auditValue, loadSchemas, lookupSchema } = require('../scripts/docs-json-field-audit.cjs');

function audit(schema, value) {
  const findings = [];
  auditValue({ value, schema, schemas: new Map(), jsonPath: '$', findings });
  return findings;
}

describe('docs JSON field audit', () => {
  const forecastPoint = {
    type: 'object',
    properties: {
      budget: { type: 'number' },
      metrics: {
        type: 'object',
        properties: { coverage_rate: { type: 'object', properties: { mid: { type: 'number' } } } },
        additionalProperties: {
          type: 'object',
          properties: { low: { type: 'number' }, mid: { type: 'number' }, high: { type: 'number' } },
        },
      },
    },
  };

  it('treats an object whose additionalProperties is a schema as an open map', () => {
    assert.deepEqual(audit(forecastPoint, { budget: 1, metrics: { clicks: { mid: 10 }, coverage_rate: { mid: 0.5 } } }), []);
  });

  it('audits open-map values against the additionalProperties schema', () => {
    const findings = audit(forecastPoint, { metrics: { clicks: { mid: 10, median: 9 } } });
    assert.deepEqual(findings.map(finding => `${finding.path}.${finding.field}`), ['$.metrics.clicks.median']);
  });

  it('still flags unknown fields on closed objects', () => {
    const findings = audit(forecastPoint, { budget: 1, spend: 2 });
    assert.deepEqual(findings.map(finding => finding.field), ['spend']);
  });

  it('resolves a generated wire response through the status body it composes', () => {
    // The wire response is generated by the schema build, not a source file.
    // A field that only the submitted body declares is known through the
    // union's submitted branch; one unknown field is the only finding.
    const schemas = loadSchemas();
    const wire = lookupSchema(schemas, '/schemas/media-buy/create-media-buy-wire-response.json');
    assert.ok(wire, 'the generated wire response is built from the source tree');
    const run = (value) => {
      const findings = [];
      auditValue({ value, schema: wire, schemas, jsonPath: '$', findings });
      return findings.map(finding => `${finding.path}.${finding.field}`);
    };
    const control = { status: 'submitted', task_id: 'task_1', expected_confirmation_at: '2026-10-30T12:00:00Z' };
    assert.deepEqual(run(control), []);
    assert.deepEqual(run({ ...control, not_a_field: true }), ['$.not_a_field']);
  });
});
