#!/usr/bin/env node
// Modular TypeScript codegen with json-schema-to-typescript (same tool as sdk-js
// scripts/generate-types.ts).
//
//   core/schemas/             -> packages/core/src/index.ts         (@adcp/core, no imports)
//   packages/<ext>/dist/bundle.json -> packages/<ext>/src/index.ts  (imports type names from @adcp/core)
//                                   -> packages/<ext>/src/index.mjs (the same module, types erased)
//
// Core refs inside an extension bundle become `tsType` references to the core
// package's exported names, so extension packages never re-declare core types.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';
import { loadCoreSchemas } from '../lib/core-schemas.mjs';
import { extensionPackages } from './build-extensions.mjs';
import { JSTS_OPTIONS, generateExtensionTs, mapRefs, hookInfo, stripRoot, toSafeString, transpileExtensionTs } from './codegen-lib.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Core surfaces exported by @adcp/core in this example (sdk-js generates all of them).
const CORE_ROOTS = [
  '/schemas/core/platform-extension-ref.json',
  '/schemas/core/extension-entry.json',
  '/schemas/core/extension-declaration.json',
  '/schemas/core/extension-branch-id.json',
  '/schemas/pricing-options/extension-option.json',
  '/schemas/enums/channels.json',
  '/schemas/core/duration.json',
  '/schemas/core/format-option-ref.json',
  '/schemas/pricing-options/price-breakdown.json',
  '/schemas/pricing-options/cpm-option.json',
  '/schemas/pricing-options/cpp-option.json',
  '/schemas/media-buy/commercial-terms.json',
  '/schemas/core/context.json',
  '/schemas/enums/task-status.json',
];

const defKey = (id) => id.replace(/^\/schemas\//, '').replace(/\.json$/, '').replace(/[^A-Za-z0-9]+/g, '_');

// ---- core ---------------------------------------------------------------
const core = new Map(loadCoreSchemas().map((s) => [s.id, s.schema]));
const needed = new Set();
const visit = (id) => {
  if (needed.has(id)) return;
  needed.add(id);
  mapRefs(core.get(id), (ref) => {
    if (ref.startsWith('/schemas/')) visit(ref.split('#')[0]);
  });
};
CORE_ROOTS.forEach(visit);

const definitions = {};
for (const id of needed) {
  const { $id, $schema, ...schema } = core.get(id);
  definitions[defKey(id)] = mapRefs(schema, (ref, n) => {
    if (ref.startsWith('#')) return { ...n, $ref: `#/definitions/${defKey(id)}${ref.slice(1)}` };
    if (!ref.startsWith('/schemas/')) return null;
    const [file, frag = ''] = ref.split('#');
    return { ...n, $ref: `#/definitions/${defKey(file)}${frag}` };
  });
}
// Extension payloads are opaque to core. jsts would emit `{ [k: string]: unknown }`,
// which TypeScript interfaces (every generated extension type) are not assignable to.
// `object` keeps core extension-agnostic and lets typed extension data flow in.
definitions[defKey('/schemas/core/extension-entry.json')].properties.data.tsType = 'object';
definitions[defKey('/schemas/core/extension-declaration.json')].properties.capabilities.tsType = 'object';

// The kernel's task union has no wire object of its own to compile: an extension task is a transport
// name in a declaration plus two definitions in the extension bundle. The SDK types it once, here,
// and each extension module generates descriptors of this type (scripts/codegen-lib.mjs).
const CONTRIBUTED_TASK = `
/**
 * A task an extension contributes: a branch of the kernel's \`task\` union (core/extension-declaration.json).
 * \`id\` is the task id (<uri>#<task>); \`request\` and \`response\` name the bundle definitions that
 * type it. Each extension module generates one descriptor per task; the buyer client calls it and the
 * seller server handles it.
 */
export interface ContributedTask<Request = object, Response = object> {
  readonly id: string;
  readonly uri: string;
  readonly digest: string;
  readonly branch: string;
  readonly request: string;
  readonly response: string;
  /** Type-level only: the request and response types. Never set at runtime. */
  readonly __types?: { request: Request; response: Response };
}
`;

const coreTs = stripRoot(
  await compile({ title: 'AdcpCoreTypes', type: 'object', additionalProperties: false, definitions }, 'AdcpCoreTypes', {
    ...JSTS_OPTIONS,
    bannerComment: `/* Generated by scripts/codegen.mjs from core/schemas (adcp-main + core/patches.json). Do not edit.\n * @adcp/core has no dependency on any extension package. */`,
  }),
  'AdcpCoreTypes'
);
mkdirSync(path.join(ROOT, 'packages/core/src'), { recursive: true });
writeFileSync(path.join(ROOT, 'packages/core/src/index.ts'), coreTs + CONTRIBUTED_TASK);
const coreExports = new Set([...(coreTs + CONTRIBUTED_TASK).matchAll(/^export (?:interface|type) (\w+)/gm)].map((m) => m[1]));
console.log(`@adcp/core: ${coreExports.size} exported types from ${needed.size} core schemas`);

/** Name @adcp/core exports for a core $id (jsts names a definition after its title). */
export function coreTypeName(id) {
  const schema = core.get(id);
  const name = toSafeString(schema?.title ?? defKey(id));
  if (!coreExports.has(name)) throw new Error(`core type for ${id} (${name}) is not exported by @adcp/core`);
  return name;
}

// ---- extensions ----------------------------------------------------------
// Hooks come from core's annotations; codegen has no list of extension points or unions.
const hooks = hookInfo();
for (const dir of extensionPackages()) {
  const bundle = JSON.parse(readFileSync(path.join(dir, 'dist/bundle.json'), 'utf8'));
  const lock = JSON.parse(readFileSync(path.join(dir, 'extension.lock.json'), 'utf8'));
  const out = await generateExtensionTs({ bundle, lock, coreTypeName, hooks });
  mkdirSync(path.join(dir, 'src'), { recursive: true });
  writeFileSync(path.join(dir, 'src/index.ts'), out);
  // The same module as JavaScript, for plain-JS sellers and tools (types erased).
  writeFileSync(path.join(dir, 'src/index.mjs'), transpileExtensionTs(out));
  console.log(`${path.basename(dir)}: imports { ${out.match(/^import type \{ (.*) \} from/m)[1]} } from @adcp/core`);
}
