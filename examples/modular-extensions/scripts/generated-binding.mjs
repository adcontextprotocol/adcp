// The generated binding: one app's typed AdCP layer, from adcp.config.json.
//
// scripts/adcp-sdk.mjs resolves the config (uri@range or a digest pin) against the registry and
// the pinned core, and calls generateBinding() to write <appDir>/adcp-sdk/:
//
//   bindings.ts      BINDING: the extensions keyed by uri@digest (attribute, version, the hooks each
//                    fills, its tasks) and, per message, where the hooks sit (layout)
//   types.ts         the app's types: CommercialTerms with one attribute per extension, MediaBuyState,
//                    PricingOption with a member per enabled branch, Proposal, MediaBuy, Tasks,
//                    Client (one method per contributed task), Server (one handler per task)
//   index.ts         createClient(), createServer(), parse(), serialize(), termsDigest(), wireSchema(),
//                    and the extensions' own types
//   bundles/         the pinned bundles (sha256 of each file = its digest)
//   GENERATED.json   what was generated from what
//
// It composes the core tree at generation time and never writes into the core package or the SDK:
// a walk from each message's root schema finds every hook the core declares (x-adcp-extension-point,
// x-adcp-open-union) and records its path. The types re-point only the hook hosts; every other core
// type stays the core package's. The runtime is lib/binding.mjs.
//
// Several versions of one uri may be enabled side by side: each is its own attribute (the config key),
// keyed by uri@digest, and its types take a version suffix (SellerAdjustableTermsV1_0_0).
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCoreSchemas } from '../lib/core-schemas.mjs';
import { refKey, sha256Digest } from '../lib/digest.mjs';
import { toSafeString } from './codegen-lib.mjs';
import { placement } from './build-core.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const HEADER = '// GENERATED by scripts/adcp-sdk.mjs from adcp.config.json. Do not edit.';

/**
 * The messages the SDK reads and writes, and the core schema each one validates against (lib/client.mjs,
 * lib/server.mjs). A prefix with '*' means: every item of that array is one such document.
 */
export const MESSAGES = {
  commercial_terms: [[[], '/schemas/media-buy/commercial-terms.json']],
  proposal: [[[], '/schemas/core/canonical-proposal.json']],
  'get_products.request': [[[], '/schemas/media-buy/get-products-request.json']],
  'get_products.response': [[['products', '*'], '/schemas/core/product.json']],
  'request_proposals.request': [[[], '/schemas/media-buy/request-proposals-request.json']],
  'request_proposals.response': [[[], '/schemas/media-buy/request-proposals-response.json']],
  'refine_proposals.request': [[[], '/schemas/media-buy/refine-proposals-request.json']],
  'refine_proposals.response': [[['proposals', '*'], '/schemas/core/canonical-proposal.json']],
  'accept_proposal.request': [[[], '/schemas/media-buy/accept-proposal-request.json']],
  'get_media_buys.response': [[[], '/schemas/media-buy/get-media-buys-response.json']],
};

/** The SDK form (lib/client.d.mts HookForms) that each core hook fills. */
const FORM_OF_HOOK = { commercial_terms: 'commercial_terms', media_buy_state: 'media_buy_state', pricing_option: 'pricing', pricing_model: 'pricing' };

const pascal = (s) => s.replace(/(^|[-_])([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const camel = (s) => s.replace(/[-_]([a-z0-9])/g, (_, c) => c.toUpperCase());
const short = (d) => `${d.slice(0, 19)}…`;

export class BindingConfigError extends Error {}

// ------------------------------------------------------------------ the walk (composition at generation time)

/**
 * Every hook reachable from a core schema: [{ path, kind, hook, ...policy, schemas: [{ id, pointer }], properties }].
 * `path` is a data path ('*' = every array item); `schemas` are the schema nodes that declare the hook there.
 */
export function hookHosts(rootId, byId = new Map(loadCoreSchemas().map((s) => [s.id, s.schema]))) {
  const resolve = (base, ref) => {
    const [file, frag = ''] = ref.split('#');
    const id = file ? (file.startsWith('/') ? file : new URL(file, `https://core${base}`).pathname) : base;
    let node = byId.get(id);
    if (!node) throw new BindingConfigError(`${base}: $ref ${ref} is not in the pinned core`);
    for (const p of frag.split('/').filter(Boolean)) node = node[decodeURIComponent(p).replace(/~1/g, '/').replace(/~0/g, '~')];
    return { id, node, pointer: frag };
  };
  const found = new Map();
  const walk = (id, node, pointer, dataPath, stack) => {
    if (!node || typeof node !== 'object') return;
    const key = `${id}#${pointer}`;
    if (stack.has(key)) return; // a recursive schema: its hooks were found on the first pass
    stack.add(key);
    const record = (h) => {
      const k = JSON.stringify([h.path, h.kind, h.hook]);
      const prev = found.get(k);
      const at = { id, pointer };
      if (prev) {
        if (!prev.schemas.some((s) => s.id === id && s.pointer === pointer)) prev.schemas.push(at);
        for (const p of h.properties) if (!prev.properties.includes(p)) prev.properties.push(p);
      } else found.set(k, { ...h, schemas: [at] });
    };
    const props = Object.keys(node.properties ?? {});
    const union = node['x-adcp-open-union'];
    if (union && (union.identity ?? 'entry') === 'entry') {
      record({ path: dataPath, kind: 'union', hook: union.name, discriminator: union.discriminator, body: union.body, unknown_in_list: union.unknown_in_list ?? 'reject', properties: props });
    }
    for (const [prop, sub] of Object.entries(node.properties ?? {})) {
      const point = sub?.['x-adcp-extension-point'];
      if (point && (point.identity ?? 'entry') === 'entry') {
        record({ path: dataPath, kind: 'point', hook: point.name, container: prop, must_understand: point.must_understand, ...(point.order ? { order: point.order } : {}), properties: props });
      }
      walk(id, sub, `${pointer}/properties/${prop.replace(/~/g, '~0').replace(/\//g, '~1')}`, [...dataPath, prop], stack);
    }
    if (typeof node.$ref === 'string') {
      const r = resolve(id, node.$ref);
      walk(r.id, r.node, r.pointer, dataPath, stack);
    }
    for (const k of ['allOf', 'anyOf', 'oneOf']) (node[k] ?? []).forEach((s, i) => walk(id, s, `${pointer}/${k}/${i}`, dataPath, stack));
    for (const k of ['if', 'then', 'else']) if (node[k]) walk(id, node[k], `${pointer}/${k}`, dataPath, stack);
    if (node.items && !Array.isArray(node.items)) walk(id, node.items, `${pointer}/items`, [...dataPath, '*'], stack);
    stack.delete(key);
  };
  walk(rootId, byId.get(rootId), '', [], new Set());
  return [...found.values()];
}

/** Top-level property names of a core schema, through $ref and allOf/anyOf/oneOf. */
function topProperties(id, byId, node = byId.get(id), seen = new Set()) {
  if (!node || typeof node !== 'object' || seen.has(node)) return [];
  seen.add(node);
  const out = Object.keys(node.properties ?? {});
  if (typeof node.$ref === 'string' && !node.$ref.startsWith('#')) {
    const target = node.$ref.split('#')[0];
    const tid = target.startsWith('/') ? target : new URL(target, `https://core${id}`).pathname;
    out.push(...topProperties(tid, byId, byId.get(tid), seen));
  }
  for (const k of ['allOf', 'anyOf', 'oneOf']) for (const s of node[k] ?? []) out.push(...topProperties(id, byId, s, seen));
  return out;
}

/**
 * The layout of every message: its roots and its hook hosts (with the message prefix applied). A request
 * that carries understood_extensions negotiates: its response may carry must-understand data only for
 * the uri@digest set the caller listed.
 */
export function messageLayout() {
  const byId = new Map(loadCoreSchemas().map((s) => [s.id, s.schema]));
  return Object.fromEntries(
    Object.entries(MESSAGES).map(([key, roots]) => [
      key,
      {
        roots,
        ...(key.endsWith('.request') ? { negotiates: roots.some(([prefix, id]) => !prefix.length && topProperties(id, byId).includes('understood_extensions')) } : {}),
        hosts: roots.flatMap(([prefix, id]) => hookHosts(id, byId).map((h) => ({ ...h, path: [...prefix, ...h.path] }))),
      },
    ])
  );
}

// ------------------------------------------------------------------ the extensions

/**
 * One enabled extension, as the generated layer binds it.
 * @param r { alias, uri, version, digest, bytes, typesFile } from scripts/adcp-sdk.mjs
 */
function extensionBinding(r, hooks) {
  const bundle = JSON.parse(r.bytes);
  const manifest = bundle['x-adcp-extension'];
  const typeName = (def) => {
    if (!bundle.definitions?.[def]) throw new BindingConfigError(`${manifest.name} ${r.version}: no definitions.${def}`);
    return toSafeString(bundle.definitions[def].title ?? def);
  };
  const b = { attribute: r.alias, name: manifest.name, version: r.version, uri: r.uri, digest: r.digest, bundle: `${manifest.name}@${r.version}.json`, hooks: {}, branches: {}, tasks: {} };
  const types = { hooks: {}, branches: {}, tasks: {} };
  for (const e of manifest.extends) {
    const hook = hooks[e.point];
    if (!hook) throw new BindingConfigError(`${manifest.name} ${r.version}: the pinned core declares no hook ${e.point}`);
    if (e.branch && hook.identity === 'enclosing') {
      b.tasks[e.branch] = { method: camel(e.branch), id: `${r.uri}#${e.branch}`, request: e.definition, response: e.response };
      types.tasks[e.branch] = { request: typeName(e.definition), response: typeName(e.response), semantics: e.semantics };
    } else if (e.branch) {
      b.branches[e.point] = { branch: e.branch, id: `${r.uri}#${e.branch}`, definition: e.definition };
      types.branches[e.point] = typeName(e.definition);
    } else if (hook.identity === 'entry') {
      b.hooks[e.point] = { definition: e.definition };
      types.hooks[e.point] = typeName(e.definition);
    } // an enclosing extension point (the capabilities fragment) belongs to the seller's declaration, not to app data
  }
  const names = [...new Set(Object.entries(bundle.definitions ?? {}).map(([def, s]) => toSafeString(s.title ?? def)))].sort();
  return { binding: b, types, names, typesFile: r.typesFile, manifest };
}

// ------------------------------------------------------------------ emitters

const rel = (from, to) => {
  const r = path.relative(from, to).split(path.sep).join('/');
  return r.startsWith('.') ? r : `./${r}`;
};
const lit = (v) => JSON.stringify(v);

function bindingsTs({ app, core, exts, layout, libDir, sdkDir }) {
  const json = JSON.stringify({ app, core, extensions: exts.map((e) => e.binding), layout }, null, 2);
  const body = json.replace(/^\{\n/, '').replace(/\n\}$/, '');
  return [
    HEADER,
    '/**',
    ' * The frozen binding of this app: the extensions it enabled, keyed by uri@digest, and where each core hook',
    ' * sits in each message the SDK reads or writes (found by walking the pinned core at generation time).',
    ' */',
    `import type { Binding } from '${rel(sdkDir, path.join(libDir, 'binding.mjs'))}';`,
    '',
    'const DATA = {',
    body + ',',
    '} as const;',
    '',
    'export const BINDING: Binding = Object.freeze({',
    `  lockfile: new URL('../adcp.lock.json', import.meta.url),`,
    `  bundles: new URL('./bundles/', import.meta.url),`,
    '  ...DATA,',
    '});',
    '',
  ].join('\n');
}

function typesTs({ core, exts, sdkDir, layout }) {
  const sdk = (f) => rel(sdkDir, path.join(ROOT, f));
  const lines = [
    HEADER,
    '/**',
    ` * This app's types: core ${core.version} plus the extensions in adcp.config.json. Extension data is a plain`,
    ' * attribute at the hook the core declares; the wire stays the extension envelope { uri, digest, data }.',
    ' */',
    `import type * as core from '${sdk('packages/core/src/index.ts')}';`,
    `import type * as sdk from '${sdk('lib/client.mjs')}';`,
    `import type { BoundClient, BoundServer } from '${sdk('lib/binding.mjs')}';`,
    ...exts.map((e) => `import type * as ${e.binding.attribute} from '${rel(sdkDir, e.typesFile)}';`),
    '',
  ];
  const doc = (e, t, def) => `  /** ${e.binding.name} ${e.binding.version} (${short(e.binding.digest)}), definitions.${def} */`;
  const attrs = (hook) =>
    exts.filter((e) => e.types.hooks[hook]).flatMap((e) => [doc(e, e.types.hooks[hook], e.binding.hooks[hook].definition), `  ${e.binding.attribute}?: ${e.binding.attribute}.${e.types.hooks[hook]};`]);
  const branchExts = exts.filter((e) => e.types.branches.pricing_model);
  const where = (hook) => [...new Set(Object.values(layout).flatMap((m) => m.hosts.filter((h) => h.hook === hook)).map((h) => h.schemas[0].id))].join(', ') || 'no message this app handles';

  // commercial_terms
  const ct = attrs('commercial_terms');
  const omit = branchExts.length ? "'extensions' | 'purchases'" : "'extensions'";
  lines.push(
    `/** commercial_terms (extension point, must_understand always, in ${where('commercial_terms')}). Wire: extensions[]. */`,
    `export type CommercialTerms = Omit<core.CommercialTerms, ${omit}> & {`,
    ...(branchExts.length ? ['  purchases: [Purchase, ...Purchase[]];'] : []),
    ...ct,
    '};',
    ''
  );
  if (branchExts.length) lines.push('/** A purchase whose pricing may be a branch of the pricing_model union that this app enabled. */', 'export type Purchase = Omit<core.ProductPurchase, \'pricing\'> & { pricing?: PricingOption };', '');

  // media_buy_state
  const mbs = attrs('media_buy_state');
  lines.push(`/** media_buy_state (extension point, must_understand never: readback on each media buy). Wire: extensions_state[]. */`, mbs.length ? `export interface MediaBuyState {\n${mbs.join('\n')}\n}` : 'export type MediaBuyState = {};', '');

  // pricing: the pricing_option point on core options, and a member per enabled pricing_model branch
  const po = attrs('pricing_option');
  lines.push('/** Attributes at the pricing_option extension point (must_understand flag) of a core pricing option. Wire: extensions[]. */', po.length ? `export interface PricingOptionAttributes {\n${po.join('\n')}\n}` : 'export type PricingOptionAttributes = {};', '');
  const members = ['sdk.CorePricingOption & PricingOptionAttributes'];
  for (const e of branchExts) {
    const br = e.binding.branches.pricing_model;
    const name = `${pascal(br.branch)}PricingOption`;
    members.push(name);
    lines.push(
      `/** pricing_model branch ${br.branch} of ${e.binding.name} ${e.binding.version} (${short(e.binding.digest)}). Wire: pricing_model ${lit(br.id)} and extension_model { uri, digest, data }. */`,
      `export type ${name} = Omit<sdk.CorePricingOption, 'pricing_model' | 'fixed_price' | 'floor_price'> & {`,
      `  pricing_model: ${lit(br.id)};`,
      `  /** definitions.${br.definition} */`,
      `  ${e.binding.attribute}: ${e.binding.attribute}.${e.types.branches.pricing_model};`,
      '};',
      ''
    );
  }
  lines.push('/** A pricing option: a core pricing model, or a branch of the pricing_model union that this app enabled. */', `export type PricingOption = ${members.join(' | ')};`, '');

  lines.push(
    '/** What this app puts at each hook of the SDK types. */',
    'export interface Forms {',
    '  commercial_terms: CommercialTerms;',
    '  media_buy_state: MediaBuyState;',
    '  pricing: PricingOption;',
    '}',
    'export type Proposal = sdk.Proposal<Forms>;',
    'export type MediaBuy = sdk.MediaBuy<Forms>;',
    'export type CanonicalProduct = sdk.CanonicalProduct<Forms>;',
    'export type Product = sdk.Product<Forms>;',
    'export type RequestProposalsResponse = sdk.RequestProposalsResponse<Forms>;',
    '',
    '/** The messages parse() and serialize() map between the wire and these types. */',
    'export interface Messages {',
    '  commercial_terms: CommercialTerms;',
    '  proposal: Proposal;',
    "  'get_products.response': { products?: Product[] };",
    "  'request_proposals.response': RequestProposalsResponse;",
    "  'refine_proposals.response': { proposals: Proposal[] };",
    "  'get_media_buys.response': { media_buys: MediaBuy[] };",
    '}',
    '',
    `/** The extensions this layer binds, by attribute. */`,
    `export type Attribute = ${exts.length ? exts.map((e) => lit(e.binding.attribute)).join(' | ') : 'never'};`,
    ''
  );

  const tasks = exts.flatMap((e) => Object.entries(e.types.tasks).map(([branch, t]) => ({ e, branch, t, b: e.binding.tasks[branch] })));
  lines.push(
    '/** The tasks this app\'s extensions contribute: request and response types from each extension\'s schema. */',
    tasks.length ? 'export interface Tasks {' : 'export type Tasks = {};',
    ...tasks.flatMap(({ e, branch, t, b }) => [
      `  /** ${e.binding.name} ${e.binding.version}: task id ${b.id} */`,
      `  ${branch}: { request: ${e.binding.attribute}.${t.request}; response: ${e.binding.attribute}.${t.response} };`,
    ]),
    ...(tasks.length ? ['}'] : []),
    '',
    '/** The buyer client: core tasks with this app\'s types, and one method per contributed task. */',
    'export interface Client extends BoundClient<Forms> {',
    ...tasks.flatMap(({ e, b, t }) => [
      `  /** ${b.id.split('#')[1]} (${e.binding.name} ${e.binding.version}), under the transport name the seller declares.${t.semantics ? ` ${t.semantics}` : ''} */`,
      `  ${b.method}(request: ${e.binding.attribute}.${t.request}): Promise<${e.binding.attribute}.${t.response}>;`,
    ]),
    '}',
    '',
    '/** The seller server: one typed handler per core task and per contributed task. */',
    'export type Server = BoundServer<Forms, Tasks, Attribute>;',
    ''
  );
  return lines.join('\n');
}

function indexTs({ core, exts, sdkDir, libDir }) {
  const reexports = [];
  const taken = new Map();
  for (const e of exts) {
    const names = e.names.map((n) => {
      const as = `${n}${e.suffix}`;
      const owner = taken.get(as);
      if (owner && owner !== e.binding.uri) throw new BindingConfigError(`type ${as} is defined by ${owner} and ${e.binding.uri}; enable one, or give one a different attribute`);
      taken.set(as, e.binding.uri);
      return as === n ? n : `${n} as ${as}`;
    });
    reexports.push(`export type { ${names.join(', ')} } from '${rel(sdkDir, e.typesFile)}';`);
  }
  return [
    HEADER,
    '/**',
    ` * This app's typed AdCP layer (generated binding): core ${core.version} plus the extensions in adcp.config.json.`,
    ...exts.map((e) => ` *   ${e.binding.attribute}: ${e.binding.name} ${e.binding.version} (${e.binding.digest})`),
    ' * Read and write extension data as plain attributes; the wire stays the extension envelope.',
    ' */',
    `import * as rt from '${rel(sdkDir, path.join(libDir, 'binding.mjs'))}';`,
    "import { BINDING } from './bindings.ts';",
    "import type { Attribute, Client, CommercialTerms, Messages, Server } from './types.ts';",
    '',
    "export type * from './types.ts';",
    ...reexports,
    'export { BINDING };',
    '',
    'const validate = rt.bindingValidator(BINDING);',
    '',
    '/** The buyer client for this app. */',
    'export function createClient(options: rt.ClientOptions): Promise<Client> {',
    '  return rt.createBoundClient(BINDING, options) as Promise<Client>;',
    '}',
    '',
    '/** The seller server for this app; `tenants` enables extensions per tenant (default: all of them). */',
    'export function createServer(options?: rt.ServerOptions<Attribute>): Server {',
    '  return rt.createBoundServer(BINDING, options) as unknown as Server;',
    '}',
    '',
    '/** Wire -> this app\'s types, for a message the SDK validated. Errors carry wire locations. */',
    'export function parse<K extends keyof Messages>(message: K, wire: unknown): Messages[K] {',
    '  return rt.decode(wire, BINDING.layout[message].hosts, BINDING.extensions, message) as Messages[K];',
    '}',
    '',
    '/** This app\'s types -> wire, with the extension data validated against the pinned bundles. Errors carry wire locations. */',
    'export function serialize<K extends keyof Messages>(message: K, value: Messages[K]): unknown {',
    '  return rt.encode(value, BINDING.layout[message].hosts, BINDING.extensions, validate, message);',
    '}',
    '',
    '/** terms_digest of commercial_terms given as attributes: sha256 of the JCS bytes of their wire form. */',
    'export function termsDigest(terms: CommercialTerms): string {',
    '  return rt.boundTermsDigest(BINDING, terms);',
    '}',
    '',
    '/** The JSON Schema a peer writes against for a message: the wire form, annotated with this build\'s uri@digest set. */',
    'export function wireSchema(message: keyof Messages | `${string}.request`): object {',
    '  return rt.wireSchema(BINDING, message);',
    '}',
    '',
    '/** The uri@digest of every extension this layer binds (what requests list in understood_extensions). */',
    'export function understoodExtensions(): { uri: string; digest: string }[] {',
    '  return BINDING.extensions.map(({ uri, digest }) => ({ uri, digest }));',
    '}',
    '',
  ].join('\n');
}

/**
 * The files of one app's generated layer, relative to <appDir>/adcp-sdk/.
 * @param resolved [{ alias, uri, version, digest, bytes, typesFile }]
 */
export function generateBinding({ appDir, release, core: coreIn, coreBundleDigest, resolved, hooks }) {
  const sdkDir = path.join(appDir, 'adcp-sdk');
  const libDir = path.join(ROOT, 'lib');
  const core = coreIn ?? { version: release.adcp_version, bundle_digest: coreBundleDigest };
  // An app that names its modules gets the messages those modules (and the kernel layer) own, and no others.
  const owner = core.modules ? placement() : null;
  const owned = (id) => core.modules[owner[id.replace(/^\/schemas\//, '')]];
  const layout = Object.fromEntries(Object.entries(messageLayout()).filter(([, m]) => !owner || m.roots.every(([, id]) => owned(id))));
  for (const r of resolved) {
    if (!/^[a-z][a-z0-9_]*$/.test(r.alias)) throw new BindingConfigError(`extensions.${r.alias}: the key is the attribute name; use snake_case (makegood_units)`);
  }
  if (new Set(resolved.map((r) => refKey(r.uri, r.digest))).size !== resolved.length) throw new BindingConfigError('each uri@digest once per build');
  const exts = [...resolved].sort((a, b) => (a.alias < b.alias ? -1 : 1)).map((r) => extensionBinding(r, hooks));
  // Versions of one uri: the highest keeps the plain type names, the others take a version suffix.
  for (const e of exts) {
    const versions = exts.filter((x) => x.binding.uri === e.binding.uri).map((x) => x.binding.version);
    const highest = versions.sort((a, b) => b.localeCompare(a, undefined, { numeric: true }))[0];
    e.suffix = e.binding.version === highest ? '' : `V${e.binding.version.replace(/\./g, '_')}`;
  }
  // An attribute must not shadow a core property of any host it lands on, and one extension lands on a host once.
  for (const m of Object.values(layout)) {
    for (const h of m.hosts) {
      const here = exts.filter((e) => (h.kind === 'point' ? e.binding.hooks[h.hook] : e.binding.branches[h.hook]));
      for (const e of here) {
        if (h.properties.includes(e.binding.attribute)) throw new BindingConfigError(`extensions.${e.binding.attribute}: ${h.hook} hosts already have a core property ${e.binding.attribute}; choose another key`);
        const twice = m.hosts.filter((o) => o.path.join('.') === h.path.join('.') && (o.kind === 'point' ? e.binding.hooks[o.hook] : e.binding.branches[o.hook]));
        if (twice.length > 1) throw new BindingConfigError(`${e.binding.name}: registers ${twice.map((o) => o.hook).join(' and ')}, which share a host; its attribute would be ambiguous`);
      }
    }
  }
  const app = path.basename(appDir);
  const files = new Map();
  files.set('bindings.ts', bindingsTs({ app, core, exts, layout, libDir, sdkDir }));
  files.set('types.ts', typesTs({ core, exts, sdkDir, layout }));
  files.set('index.ts', indexTs({ core, exts, sdkDir, libDir }));
  for (const r of resolved) files.set(`bundles/${JSON.parse(r.bytes)['x-adcp-extension'].name}@${r.version}.json`, r.bytes);
  files.set(
    'GENERATED.json',
    JSON.stringify(
      {
        generator: 'scripts/adcp-sdk.mjs (generated binding)',
        core,
        extensions: Object.fromEntries(exts.map((e) => [e.binding.attribute, { name: e.binding.name, version: e.binding.version, uri: e.binding.uri, digest: e.binding.digest, hooks: Object.keys(e.binding.hooks), branches: Object.keys(e.binding.branches), tasks: Object.keys(e.binding.tasks) }])),
      },
      null,
      2
    ) + '\n'
  );
  for (const r of resolved) if (sha256Digest(r.bytes) !== r.digest) throw new BindingConfigError(`${r.uri}@${r.version}: bytes do not hash to ${r.digest}`);
  return files;
}
